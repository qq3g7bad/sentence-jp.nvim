local h = require("tests.helpers")

describe("sentence ending", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  it("does not split at a decimal point", function()
    h.buf({ "バージョン0.11を使う。次。" })
    h.at(1, "使")
    h.normal("dis")
    assert.same({ "次。" }, h.get())
  end)

  it("does not split at dots inside a URL", function()
    h.buf({ "See https://example.com/a.b today. Next." })
    h.at(1, "today")
    h.normal("dis")
    assert.same({ " Next." }, h.get())
  end)

  it("does not split at a dot in a file name", function()
    h.buf({ "前。init.lua を編集する。後。" })
    h.at(1, "編集")
    h.normal("dis")
    assert.same({ "前。後。" }, h.get())
  end)

  it("splits English sentences separated by a space", function()
    h.buf({ "Hello. World." })
    h.at(1, "World")
    h.normal("dis")
    assert.same({ "Hello. " }, h.get())
  end)

  it("includes closing quotes after English punctuation", function()
    h.buf({ 'He said "Go." Then left.' })
    h.at(1, "Then")
    h.normal("dis")
    assert.same({ 'He said "Go." ' }, h.get())
  end)

  it(") does not stop inside a decimal number", function()
    h.buf({ "バージョン0.11を使う。次。" })
    h.at(1, "バ")
    h.normal(")")
    assert.equals("1:次。", h.ch())
  end)

  it("( does not stop inside a decimal number", function()
    h.buf({ "前。バージョン0.11を使う。" })
    h.at(1, "使")
    h.normal("(")
    assert.equals("1:バー", h.ch())
  end)
end)
