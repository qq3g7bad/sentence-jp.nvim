local h = require("tests.helpers")

describe("motions", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  it(") moves to the start of each following sentence", function()
    h.buf({ "First. 最初の文。次の文。Last." })
    h.at(1, "First")
    h.normal(")")
    assert.equals("1:最初", h.ch())
    h.normal(")")
    assert.equals("1:次の", h.ch())
    h.normal(")")
    assert.equals("1:La", h.ch())
  end)

  it("( moves back to the start of each preceding sentence", function()
    h.buf({ "First. 最初の文。次の文。Last." })
    h.at(1, "Last")
    h.normal("(")
    assert.equals("1:次の", h.ch())
    h.normal("(")
    assert.equals("1:最初", h.ch())
    h.normal("(")
    assert.equals("1:Fi", h.ch())
  end)
end)

describe("motions across lines and paragraphs", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  it("( does not stop at the start of a wrapped line", function()
    h.buf({ "これは長い", "文です。次。" })
    h.at(2, "です")
    h.normal("(")
    assert.equals("1:これ", h.ch())
  end)

  it(") does not stop at the start of a wrapped line", function()
    h.buf({ "前。これは長い", "文です。次。" })
    h.at(1, "これ")
    h.normal(")")
    assert.equals("2:次。", h.ch())
  end)

  it("3) and 3( go back and forth", function()
    h.buf({ "一。二。", "三。四。五。" })
    h.at(1, "一")
    h.normal("3)")
    assert.equals("2:四。", h.ch())
    h.normal("3(")
    assert.equals("1:一。", h.ch())
  end)

  it(") stops at a blank line, then moves to the next paragraph", function()
    h.buf({ "A。", "", "B。" })
    h.at(1, "A")
    h.normal(")")
    assert.same({ 2, 0 }, vim.api.nvim_win_get_cursor(0))
    h.normal(")")
    assert.equals("3:B。", h.ch())
  end)

  it("( stops at a blank line, then moves to the last sentence of the previous paragraph", function()
    h.buf({ "A。B。", "", "C。" })
    h.at(3, "C")
    h.normal("(")
    assert.same({ 2, 0 }, vim.api.nvim_win_get_cursor(0))
    h.normal("(")
    assert.equals("1:B。", h.ch())
  end)

  it(") from whitespace between sentences goes to the next sentence", function()
    h.buf({ "A.  B." })
    vim.api.nvim_win_set_cursor(0, { 1, 2 })
    h.normal(")")
    assert.equals("1:B.", h.ch())
  end)

  it("d( deletes back to the sentence start across lines", function()
    h.buf({ "前。これは長い", "文です。" })
    h.at(2, "です")
    h.normal("d(")
    assert.same({ "前。です。" }, h.get())
  end)
end)

describe(") on the last sentence", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  it("d) deletes to the end of the buffer", function()
    h.buf({ "Hi. There." })
    h.at(1, "There")
    h.normal("d)")
    assert.same({ "Hi. " }, h.get())
  end)

  it("d) deletes to the end of the line before a blank line", function()
    h.buf({ "Hi. There.", "", "x" })
    h.at(1, "There")
    h.normal("d)")
    assert.same({ "Hi. ", "", "x" }, h.get())
  end)

  it(") stops at the last character of the buffer", function()
    h.buf({ "前。最後。" })
    h.at(1, "最後")
    h.normal(")")
    assert.equals("1:。", h.ch())
    h.normal(")")
    assert.equals("1:。", h.ch())
  end)

  it("3) stops at the last character when there are fewer sentences", function()
    h.buf({ "一。二。" })
    h.at(1, "一")
    h.normal("3)")
    assert.equals("1:。", h.ch())
  end)
end)
