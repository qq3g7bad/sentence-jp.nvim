local h = require("tests.helpers")

describe("paragraph boundaries", function()
  after_each(function()
    require("sentence-jp").setup()
  end)

  it("is does not cross a line of fullwidth spaces", function()
    require("sentence-jp").setup()
    h.buf({ "前の段落", "　　", "次の段落。" })
    h.at(3, "次")
    h.normal("dis")
    assert.same({ "前の段落", "　　", "" }, h.get())
  end)

  it(") stops at a line of fullwidth spaces", function()
    require("sentence-jp").setup()
    h.buf({ "A。", "　", "B。" })
    h.at(1, "A")
    h.normal(")")
    assert.same({ 2, 0 }, vim.api.nvim_win_get_cursor(0))
  end)

  it("treats a fullwidth-space line as text when include_fullwidth_space is false", function()
    require("sentence-jp").setup({ include_fullwidth_space = false })
    h.buf({ "前の段落", "　　", "次の段落。" })
    h.at(3, "次")
    h.normal("dis")
    assert.same({ "" }, h.get())
  end)
end)
