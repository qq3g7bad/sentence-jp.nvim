local h = require("tests.helpers")

describe("closing brackets (quote_aware = true)", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  it("keeps a quoted sentence inside the outer sentence", function()
    h.buf({ "前。彼は「行く。」と言った。次。" })
    h.at(1, "と言")
    h.normal("dis")
    assert.same({ "前。次。" }, h.get())
  end)

  it(") does not stop at a closing bracket inside a sentence", function()
    h.buf({ "彼は「行く。」と言った。次。" })
    h.at(1, "彼")
    h.normal(")")
    assert.equals("1:次。", h.ch())
  end)

  it("includes the closer when the line ends after it", function()
    h.buf({ "「はい。」", "次の文。" })
    h.at(1, "はい")
    h.normal("dis")
    assert.same({ "", "次の文。" }, h.get())
  end)

  it("splits consecutive quoted sentences", function()
    h.buf({ "「はい。」「いいえ。」" })
    h.at(1, "いいえ")
    h.normal("dis")
    assert.same({ "「はい。」" }, h.get())
  end)

  it("includes nested closers", function()
    h.buf({ "前。（「はい。」）", "次。" })
    h.at(1, "はい")
    h.normal("dis")
    assert.same({ "前。", "次。" }, h.get())
  end)
end)

describe("closing brackets (quote_aware = false)", function()
  before_each(function()
    require("sentence-jp").setup({ quote_aware = false })
  end)

  after_each(function()
    require("sentence-jp").setup()
  end)

  it("always ends the sentence after the closer", function()
    h.buf({ "彼は「行く。」と言った。" })
    h.at(1, "と言")
    h.normal("dis")
    assert.same({ "彼は「行く。」" }, h.get())
  end)
end)
