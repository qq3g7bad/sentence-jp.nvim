local h = require("tests.helpers")

local function cursor()
  return vim.api.nvim_win_get_cursor(0)
end

describe("list items", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  after_each(function()
    require("sentence-jp").setup()
  end)

  local lines = { "前の文です。", "- 項目A", "- 項目B", "- 項目C" }

  it("dis selects only the text of the item", function()
    h.buf(lines)
    h.at(4, "C")
    h.normal("dis")
    assert.same({ "前の文です。", "- 項目A", "- 項目B", "- " }, h.get())
  end)

  it("das deletes the item text with its marker", function()
    h.buf(lines)
    h.at(3, "B")
    h.normal("das")
    assert.same({ "前の文です。", "- 項目A", "", "- 項目C" }, h.get())
  end)

  it("das includes the indent and checkbox of the item", function()
    h.buf({ "- 親", "  - [ ] 子" })
    h.at(2, "子")
    h.normal("das")
    assert.same({ "- 親", "" }, h.get())
  end)

  it("das keeps the marker when the sentence has trailing whitespace", function()
    h.buf({ "- 一文目。 二文目。" })
    h.at(1, "一")
    h.normal("das")
    assert.same({ "- 二文目。" }, h.get())
  end)

  it("das on a later sentence of the item keeps the marker", function()
    h.buf({ "- 一文目。二文目。" })
    h.at(1, "二")
    h.normal("das")
    assert.same({ "- 一文目。" }, h.get())
  end)

  it("v2as selects the next item with the first marker", function()
    h.buf(lines)
    h.at(2, "項")
    h.normal("v2asd")
    assert.same({ "前の文です。", "", "- 項目C" }, h.get())
  end)

  it("vas extended backward includes the markers of the items", function()
    h.buf(lines)
    h.at(3, "B")
    -- "as" grows the backward selection to the start of "- 項目B", then to "- 項目A"
    h.normal("vhasd")
    assert.same({ "前の文です。", "- 項目A", "", "- 項目C" }, h.get())
    h.buf(lines)
    h.at(3, "B")
    h.normal("vhasasd")
    assert.same({ "前の文です。", "", "- 項目C" }, h.get())
  end)

  it("dis on the marker selects the text of the item", function()
    h.buf(lines)
    h.at(3, "-")
    h.normal("dis")
    assert.same({ "前の文です。", "- 項目A", "- ", "- 項目C" }, h.get())
  end)

  it("dis on the text before the list does not include the list", function()
    h.buf({ "前の文", "- 項目A" })
    h.at(1, "前")
    h.normal("dis")
    assert.same({ "", "- 項目A" }, h.get())
  end)

  it("splits sentences inside an item and keeps continuation lines", function()
    h.buf({ "- 一文目。二文目が", "  続く。", "- 次" })
    h.at(2, "続")
    h.normal("dis")
    assert.same({ "- 一文目。", "- 次" }, h.get())
  end)

  it("supports numbered items, nested items and checkboxes", function()
    h.buf({ "1. 一つ目", "  * 入れ子", "- [ ] タスク" })
    h.at(2, "入")
    h.normal("dis")
    h.at(3, "タ")
    h.normal("dis")
    assert.same({ "1. 一つ目", "  * ", "- [ ] " }, h.get())
  end)

  it(") moves to the text of the next item", function()
    h.buf(lines)
    h.at(2, "項")
    h.normal(")")
    assert.same("3:項目", h.ch())
  end)

  it("( moves to the text of the previous item", function()
    h.buf(lines)
    h.at(3, "項")
    h.normal("(")
    assert.same("2:項目", h.ch())
    h.normal("(")
    assert.same("1:前の", h.ch())
  end)

  it(") from a blank line moves to the text of the item", function()
    h.buf({ "前。", "", "- 項目" })
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    h.normal(")")
    assert.same("3:項目", h.ch())
  end)

  it("v2is extends over the next item", function()
    h.buf(lines)
    h.at(2, "項")
    h.normal("v2isd")
    assert.same({ "前の文です。", "- ", "- 項目C" }, h.get())
  end)

  it("vis extended backward stops at the text of the previous item", function()
    h.buf(lines)
    h.at(3, "B")
    -- "is" grows the backward selection to the start of "項目B", then to "項目A"
    h.normal("vhisisd")
    assert.same({ "前の文です。", "- ", "- 項目C" }, h.get())
  end)

  it("runs items together like Vim when list_items.enable is false", function()
    require("sentence-jp").setup({ list_items = { enable = false } })
    h.buf(lines)
    h.at(4, "C")
    h.normal("dis")
    assert.same({ "前の文です。", "" }, h.get())
  end)

  it("uses a custom pattern", function()
    require("sentence-jp").setup({ list_items = { pattern = "^・" } })
    h.buf({ "・項目A", "・項目B", "- 項目C" })
    h.at(2, "B")
    h.normal("dis")
    assert.same({ "・項目A", "・" }, h.get())
  end)
end)
