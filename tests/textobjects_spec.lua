local h = require("tests.helpers")

describe("text objects", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  it("dis deletes an English sentence between Japanese ones", function()
    h.buf({ "おはようございます。Hello world. さようなら。" })
    h.at(1, "Hello")
    h.normal("dis")
    assert.same({ "おはようございます。 さようなら。" }, h.get())
  end)

  it("dis deletes a Japanese sentence", function()
    h.buf({ "おはようございます。Hello world. さようなら。" })
    h.at(1, "おはよう")
    h.normal("dis")
    assert.same({ "Hello world. さようなら。" }, h.get())
  end)

  it("das deletes a sentence with its trailing space", function()
    h.buf({ "おはようございます。Hello world. さようなら。" })
    h.at(1, "Hello")
    h.normal("das")
    assert.same({ "おはようございます。さようなら。" }, h.get())
  end)

  it("includes a run of consecutive punctuation", function()
    h.buf({ "前の文。連続した句読点にも対応します。。。次の文。" })
    h.at(1, "連続")
    h.normal("dis")
    assert.same({ "前の文。次の文。" }, h.get())
  end)

  it("treats a sentence wrapped across lines as one", function()
    h.buf({ "前の文。これは長い", "文です。次。" })
    h.at(2, "です")
    h.normal("dis")
    assert.same({ "前の文。次。" }, h.get())
  end)
end)

describe("as at the end of a line", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  it("does not take whitespace from the next line (English)", function()
    h.buf({ "Hello world.", "Next sentence here." })
    h.at(1, "Hello")
    h.normal("das")
    assert.same({ "", "Next sentence here." }, h.get())
  end)

  it("does not take whitespace from the next line (Japanese)", function()
    h.buf({ "日本語の文。", "次の 文です。" })
    h.at(1, "日本")
    h.normal("das")
    assert.same({ "", "次の 文です。" }, h.get())
  end)

  it("includes leading whitespace when there is no trailing whitespace", function()
    h.buf({ "A. B." })
    h.at(1, "B")
    h.normal("das")
    assert.same({ "A." }, h.get())
  end)

  it("includes leading fullwidth space when there is no trailing whitespace", function()
    h.buf({ "前の文。　次の文。" })
    h.at(1, "次")
    h.normal("das")
    assert.same({ "前の文。" }, h.get())
  end)
end)

describe("count and visual extension", function()
  before_each(function()
    require("sentence-jp").setup()
  end)

  -- Like Vim, "is" counts the whitespace between sentences as a unit
  it("d2is deletes a sentence and the following whitespace", function()
    h.buf({ "A. B. C. D." })
    h.at(1, "A")
    h.normal("d2is")
    assert.same({ "B. C. D." }, h.get())
  end)

  it("d3is deletes two sentences", function()
    h.buf({ "A. B. C. D." })
    h.at(1, "A")
    h.normal("d3is")
    assert.same({ " C. D." }, h.get())
  end)

  it("d2as deletes two sentences with their whitespace", function()
    h.buf({ "A. B. C. D." })
    h.at(1, "A")
    h.normal("d2as")
    assert.same({ "C. D." }, h.get())
  end)

  it("d2is deletes two Japanese sentences", function()
    h.buf({ "一。二。三。" })
    h.at(1, "一")
    h.normal("d2is")
    assert.same({ "三。" }, h.get())
  end)

  it("v2is selects two Japanese sentences across lines", function()
    h.buf({ "一。二", "続き。三。" })
    h.at(1, "一")
    h.normal("v2isd")
    assert.same({ "三。" }, h.get())
  end)

  it("stops at the end of the paragraph", function()
    h.buf({ "一。二。", "", "三。" })
    h.at(1, "一")
    h.normal("d5is")
    assert.same({ "", "", "三。" }, h.get())
  end)

  it("visis extends the selection by one unit", function()
    h.buf({ "A. B. C. D." })
    h.at(1, "A")
    h.normal("visisd")
    assert.same({ "B. C. D." }, h.get())
  end)

  it("vasas extends the selection by one sentence", function()
    h.buf({ "A. B. C. D." })
    h.at(1, "A")
    h.normal("vasasd")
    assert.same({ "C. D." }, h.get())
  end)

  it("visis extends Japanese sentences", function()
    h.buf({ "一。二。三。" })
    h.at(1, "一")
    h.normal("visisd")
    assert.same({ "三。" }, h.get())
  end)

  it("vlis extends to the end of the current unit", function()
    h.buf({ "A. B. C. D." })
    h.at(1, "A")
    h.normal("vlisd")
    assert.same({ "B. C. D." }, h.get())
  end)

  it("vhis extends backward", function()
    h.buf({ "A. B. C. D." })
    h.at(1, "D")
    h.normal("vhisd")
    assert.same({ "A. B. ." }, h.get())
  end)

  it("vis from linewise visual mode becomes characterwise", function()
    h.buf({ "一。二。三。" })
    h.at(1, "二")
    h.normal("Visd")
    assert.same({ "一。三。" }, h.get())
  end)
end)
